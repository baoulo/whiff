//! The risk vocabulary: every `security.risks[].kind` an extractor may
//! report, with its category, severity and a one-line meaning. Extractors
//! name the kind only; [`Risk::new`] fills in the rest from this table, so
//! category and severity are decided in one place. `docs/risks.md` is
//! generated from it (`whiff-dev catalogue`).

use schemars::JsonSchema;
use serde::{Deserialize, Serialize};

use super::Risk;

/// How much a risk signal should worry the reader.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize, JsonSchema)]
#[serde(rename_all = "snake_case")]
pub enum Severity {
    /// Worth knowing; not a threat by itself.
    Info,
    /// Common in benign files; a threat only together with other signals.
    Low,
    /// Can act on the reader's behalf or reach out, but is also used legitimately.
    #[default]
    Medium,
    /// Rarely legitimate, or a known exploitation or deception technique.
    High,
}

impl Severity {
    /// The `snake_case` name.
    pub fn as_str(self) -> &'static str {
        match self {
            Self::Info => "info",
            Self::Low => "low",
            Self::Medium => "medium",
            Self::High => "high",
        }
    }
}

/// What kind of threat a risk signal points to.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize, JsonSchema)]
#[serde(rename_all = "snake_case")]
pub enum RiskCategory {
    /// Code that can run: macros, scripts, actions, DDE.
    ActiveContent,
    /// Deceiving the reader: spoofed senders, misleading links, credential forms.
    Phishing,
    /// Content fetched from elsewhere when the file is opened.
    ExternalReference,
    /// Constructs tied to known exploitation techniques.
    Exploit,
    /// Content hidden from a casual look.
    Obfuscation,
    /// Secrets or credentials in the content.
    DataExposure,
    /// Installs, fetches or trusts code from elsewhere.
    SupplyChain,
    /// Operations that change or destroy state with broad privileges.
    UnsafeOperation,
    /// Where the content came from (e.g. generated by AI).
    Provenance,
    /// A kind outside the vocabulary (from a third-party extractor).
    #[default]
    Other,
}

impl RiskCategory {
    /// The `snake_case` name.
    pub fn as_str(self) -> &'static str {
        match self {
            Self::ActiveContent => "active_content",
            Self::Phishing => "phishing",
            Self::ExternalReference => "external_reference",
            Self::Exploit => "exploit",
            Self::Obfuscation => "obfuscation",
            Self::DataExposure => "data_exposure",
            Self::SupplyChain => "supply_chain",
            Self::UnsafeOperation => "unsafe_operation",
            Self::Provenance => "provenance",
            Self::Other => "other",
        }
    }
}

/// One entry of the vocabulary.
#[derive(Debug, Clone, Copy)]
pub struct RiskKind {
    /// The `snake_case` kind.
    pub kind: &'static str,
    /// Its category.
    pub category: RiskCategory,
    /// Its severity.
    pub severity: Severity,
    /// What it means, in one line.
    pub meaning: &'static str,
}

const fn k(kind: &'static str, category: RiskCategory, severity: Severity, meaning: &'static str) -> RiskKind {
    RiskKind { kind, category, severity, meaning }
}

