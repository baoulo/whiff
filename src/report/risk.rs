/// The vocabulary entry for `kind`.
pub fn classify(kind: &str) -> Option<&'static RiskKind> {
    RISK_KINDS.binary_search_by(|e| e.kind.cmp(kind)).ok().map(|i| &RISK_KINDS[i])
}

impl Risk {
    /// A risk of `kind`, with category and severity from [`RISK_KINDS`].
    /// A kind outside the vocabulary (a third-party extractor's) is
    /// `other` / `medium`; whiff's own kinds are checked by its tests.
    pub fn new(kind: impl Into<String>, detail: Option<String>, source: impl Into<String>) -> Self {
        let kind = kind.into();
        let entry = classify(&kind);
        Self {
            category: entry.map_or(RiskCategory::Other, |e| e.category),
            severity: entry.map_or(Severity::Medium, |e| e.severity),
            kind,
            detail,
            source: source.into(),
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn vocabulary_is_sorted_unique_and_snake_case() {
        for w in RISK_KINDS.windows(2) {
            assert!(w[0].kind < w[1].kind, "{} before {}", w[0].kind, w[1].kind);
        }
        for e in RISK_KINDS {
            assert!(e.kind.bytes().all(|b| b.is_ascii_lowercase() || b == b'_'), "{}", e.kind);
            assert_ne!(e.meaning, "", "{}", e.kind);
        }
    }

    #[test]
    fn every_kind_in_the_source_is_classified() {
        // Literal kinds at `.risk("…"` / `Risk::new("…"` call sites, plus the
        // ones chosen at run time.
        let dynamic = ["dde", "external_content", "double_extension", "executable_attachment", "macro_attachment"];
        let mut missing = Vec::new();
        let mut stack = vec![std::path::PathBuf::from(concat!(env!("CARGO_MANIFEST_DIR"), "/src"))];
        while let Some(dir) = stack.pop() {
            for entry in std::fs::read_dir(&dir).unwrap().flatten() {
                let path = entry.path();
                if path.is_dir() {
                    stack.push(path);
                    continue;
                }
                if path.extension().is_none_or(|e| e != "rs") || path.ends_with("risk.rs") {
                    continue;
                }
                let src = std::fs::read_to_string(&path).unwrap();
                for marker in [".risk(", "Risk::new("] {
                    for (at, _) in src.match_indices(marker) {
                        let rest = src[at + marker.len()..].trim_start();
                        let Some(rest) = rest.strip_prefix('"') else { continue };
                        let kind = &rest[..rest.find('"').unwrap_or(0)];
                        if classify(kind).is_none() {
                            missing.push(format!("{}: {kind}", path.display()));
                        }
                    }
                }
            }
        }
        for kind in dynamic {
            if classify(kind).is_none() {
                missing.push(kind.to_string());
            }
        }
        assert!(missing.is_empty(), "add these kinds to RISK_KINDS: {missing:?}");
    }

    #[test]
    fn new_fills_category_and_severity() {
        let r = Risk::new("auto_exec_macro", None, "doc.ole");
        assert_eq!((r.category, r.severity), (RiskCategory::ActiveContent, Severity::High));
        assert!(Severity::High > Severity::Medium && Severity::Low > Severity::Info);
    }
}
