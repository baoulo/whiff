//! Advanced SubStation Alpha (ASS, v4.00+) and SubStation Alpha (SSA,
//! v4.00): script information (title, authors, resolution, generator),
//! styles and their fonts, dialogue events with speakers and effects,
//! comment events, embedded fonts and graphics, and the files an Aegisub
//! project points at (names only).
//!
//! Specification: the SubStation Alpha v4.00+ script format, as libass and
//! Aegisub read it.

use std::collections::BTreeSet;

use super::{Cue, Subtitles, clock, head_text, plain_text};
use crate::plugin::{Context, Cost, ExtractError, Extractor, ExtractorMeta, FormatSpec, Probe, Sniff, Source};

/// Extractor for SSA and ASS scripts.
pub struct Ass;

static META: ExtractorMeta = ExtractorMeta {
    id: "subtitle.ass",
    version: 1,
    cost: Cost::Scan,
    priority: 0,
    formats: &[
        FormatSpec {
            id: "ass",
            name: "Advanced SubStation Alpha subtitles",
            family: "text.subtitle",
            mimes: &["text/x-ass"],
            extensions: &["ass"],
            magic: &[],
            parent: None,
        },
        FormatSpec {
            id: "ssa",
            name: "SubStation Alpha subtitles",
            family: "text.subtitle",
            mimes: &["text/x-ssa"],
            extensions: &["ssa"],
            magic: &[],
            parent: None,
        },
    ],
};

/// Names listed for fonts and attached files.
const MAX_LISTED: usize = 20;

impl Extractor for Ass {
    fn meta(&self) -> &'static ExtractorMeta {
        &META
    }

    fn sniff(&self, probe: &Probe<'_>) -> Option<Sniff> {
        let text = head_text(probe.head);
        let mut lines = text.lines().map(str::trim).filter(|l| !l.is_empty());
        if !lines.next()?.eq_ignore_ascii_case("[script info]") {
            return None;
        }
        let lower = text.to_ascii_lowercase();
        let ssa = lower.contains("scripttype: v4.00\n")
            || lower.contains("scripttype: v4.00\r")
            || (lower.contains("[v4 styles]") && !lower.contains("scripttype: v4.00+"));
        Some(Sniff { format: if ssa { "ssa" } else { "ass" }, confidence: 0.95 })
    }

    fn extract(&self, src: &mut dyn Source, cx: &mut Context<'_>) -> Result<(), ExtractError> {
        let text = cx.read_text(src)?.text;
        cx.checkpoint()?;
        let subs = parse(&text);
        if subs.cues.is_empty() {
            cx.warn("no dialogue events");
        }
        subs.report(cx);
        Ok(())
    }
}

crate::register_extractor!(Ass);

/// The file name of a path, for project files that point at local media.
fn file_name(path: &str) -> &str {
    path.trim().rsplit(['/', '\\']).next().unwrap_or("")
}

#[allow(clippy::too_many_lines)] // one pass over the sections
fn parse(text: &str) -> Subtitles {
    let mut s = Subtitles::new("ass");
    let mut section = String::new();
    let mut style_format: Vec<String> = Vec::new();
    let mut event_format: Vec<String> = Vec::new();
    let mut fonts: BTreeSet<String> = BTreeSet::new();
    let (mut embedded_fonts, mut graphics, mut comments, mut effects, mut other_events) =
        (Vec::new(), Vec::new(), 0u64, 0u64, 0u64);
    let mut project = serde_json::Map::new();
    for line in text.lines() {
        let line = line.trim_end();
        let trimmed = line.trim_start();
        if trimmed.starts_with('[') && trimmed.ends_with(']') {
            section = trimmed[1..trimmed.len() - 1].to_ascii_lowercase();
            continue;
        }
        if section == "script info" && trimmed.starts_with(';') {
            let c = trimmed[1..].trim();
            if let Some(g) = c.strip_prefix("Script generated by ") {
                s.set("generator", g.trim());
            }
            continue;
        }
        let Some((key, value)) = trimmed.split_once(':') else { continue };
        let value = value.trim();
        match section.as_str() {
            "script info" => match key.trim().to_ascii_lowercase().as_str() {
                "title" if !value.eq_ignore_ascii_case("<untitled>") => s.title = Some(value.to_string()),
                "original script" if !value.eq_ignore_ascii_case("<unknown>") => s.author = Some(value.to_string()),
                "original translation" => s.set("translation_by", value),
                "original editing" => s.set("editing_by", value),
                "original timing" => s.set("timing_by", value),
                "script updated by" => s.set("updated_by", value),
                "update details" => s.set("update_details", value),
                "scripttype" => s.set("script_type", value),
                "collisions" => s.set("collisions", value.to_ascii_lowercase()),
                "playresx" => s.set("play_res_x", value.parse::<u32>().ok()),
                "playresy" => s.set("play_res_y", value.parse::<u32>().ok()),
                "wrapstyle" => s.set("wrap_style", value.parse::<u8>().ok()),
                "ycbcr matrix" => s.set("ycbcr_matrix", value),
                "timer" => s.set("timer", value.parse::<f64>().ok()),
                _ => {}
            },
            "v4+ styles" | "v4 styles" => match key.trim() {
                "Format" => style_format = fields(value, usize::MAX),
                "Style" => {
                    let f = fields(value, style_format.len().max(1));
                    let col = |name: &str| style_format.iter().position(|c| c.eq_ignore_ascii_case(name));
                    if let Some(n) = col("Name").and_then(|i| f.get(i)) {
                        s.styles.push(n.clone());
                    }
                    if let Some(font) = col("Fontname").and_then(|i| f.get(i)).filter(|f| !f.is_empty()) {
                        fonts.insert(font.clone());
                    }
                }
                _ => {}
            },
            "events" => match key.trim() {
                "Format" => event_format = fields(value, usize::MAX),
                kind @ ("Dialogue" | "Comment") => {
                    if kind == "Comment" {
                        comments += 1;
                        continue;
                    }
                    let fmt: &[String] = if event_format.is_empty() { &DEFAULT_EVENT_FORMAT } else { &event_format };
                    let f = fields(value, fmt.len());
                    let col = |name: &str| {
                        fmt.iter().position(|c| c.eq_ignore_ascii_case(name)).and_then(|i| f.get(i)).map(String::as_str)
                    };
                    let (Some(start), end) = (col("Start").and_then(clock), col("End").and_then(clock)) else {
                        continue;
                    };
                    if col("Effect").is_some_and(|e| !e.is_empty()) {
                        effects += 1;
                    }
                    let speaker = col("Name").or_else(|| col("Actor")).filter(|n| !n.is_empty()).map(str::to_string);
                    let raw = col("Text").unwrap_or("");
                    let text = plain_text(raw, &mut s.markup);
                    s.push(Cue { start, end, text, speaker });
                }
                "Picture" | "Sound" | "Movie" | "Command" => other_events += 1,
                _ => {}
            },
            "fonts" if key.trim() == "fontname" => {
                if embedded_fonts.len() < MAX_LISTED {
                    embedded_fonts.push(value.to_string());
                }
            }
            "graphics" if key.trim() == "filename" => {
                if graphics.len() < MAX_LISTED {
                    graphics.push(value.to_string());
                }
            }
            "aegisub project garbage" => {
                let k = match key.trim() {
                    "Audio File" => "audio_file",
                    "Video File" => "video_file",
                    "Keyframes File" => "keyframes_file",
                    "Timecodes File" => "timecodes_file",
                    _ => continue,
                };
                let name = file_name(value);
                if !name.is_empty() && !name.starts_with('?') {
                    project.insert(k.into(), serde_json::json!(name));
                }
            }
            _ => {}
        }
    }
    if section.is_empty() {
        return s;
    }
    s.set("fonts", fonts.into_iter().take(MAX_LISTED).collect::<Vec<_>>());
    s.set("embedded_fonts", embedded_fonts);
    s.set("embedded_graphics", graphics);
    for (k, v) in [("comment_events", comments), ("effect_events", effects), ("other_events", other_events)] {
        if v > 0 {
            s.set(k, v);
        }
    }
    s.set("aegisub_project", serde_json::Value::Object(project));
    s
}

/// The v4.00+ event columns, for scripts without a `Format:` line.
static DEFAULT_EVENT_FORMAT: std::sync::LazyLock<Vec<String>> = std::sync::LazyLock::new(|| {
    ["Layer", "Start", "End", "Style", "Name", "MarginL", "MarginR", "MarginV", "Effect", "Text"]
        .iter()
        .map(|s| (*s).to_string())
        .collect()
});

/// Comma-separated fields; the last one keeps any further commas (the text).
fn fields(value: &str, n: usize) -> Vec<String> {
    value.splitn(n.max(1), ',').map(|f| f.trim().to_string()).collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    crate::fixture_tests!("ass", "ssa");

    #[test]
    fn script() {
        let s = parse(
            "[Script Info]\n; Script generated by Aegisub 3.2.2\nTitle: Harbour\nOriginal Script: Ana\nScriptType: v4.00+\n\n\
             [V4+ Styles]\nFormat: Name, Fontname, Fontsize\nStyle: Default,Arial,20\nStyle: Sign,Georgia,18\n\n\
             [Events]\nFormat: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text\n\
             Dialogue: 0,0:00:01.00,0:00:02.50,Default,Bob,0,0,0,,{\\k20}Hello, {\\i1}world\n\
             Comment: 0,0:00:03.00,0:00:04.00,Default,,0,0,0,,note\n\
             Dialogue: 0,0:00:03.00,0:00:04.00,Sign,,0,0,0,Banner;10,Sign\\Ntext\n\n\
             [Aegisub Project Garbage]\nVideo File: /home/someone/film.mkv\n",
        );
        assert_eq!(s.cues.len(), 2);
        assert_eq!(
            s.cues[0],
            Cue { start: 1.0, end: Some(2.5), text: "Hello, world".into(), speaker: Some("Bob".into()) }
        );
        assert_eq!(s.cues[1].text, "Sign\ntext");
        assert_eq!(s.styles, ["Default", "Sign"]);
        assert_eq!(s.format["fonts"], serde_json::json!(["Arial", "Georgia"]));
        assert_eq!(s.format["generator"], "Aegisub 3.2.2");
        assert_eq!(s.format["comment_events"], 1);
        assert_eq!(s.format["effect_events"], 1);
        assert_eq!(s.format["aegisub_project"]["video_file"], "film.mkv");
        assert!(s.markup.contains("karaoke") && s.markup.contains("italic"));
        assert_eq!((s.title.as_deref(), s.author.as_deref()), (Some("Harbour"), Some("Ana")));
        assert_eq!(parse("no sections").cues, []);
    }
}
