//! **whiff** sniffs any file and returns one JSON document describing it: what it
//! is, where it came from, who owns it, when it was made, what rights apply, its
//! physical properties, and a compact, LLM-ready view of its content.
//!
//! ```no_run
//! let engine = whiff::Engine::new();
//! let report = engine.extract_path("photo.jpg")?;
//! println!("{}", serde_json::to_string_pretty(&report)?);
//! # Ok::<(), Box<dyn std::error::Error>>(())
//! ```
//!
//! Format support is split into cargo features: `common` (default) plus the
//! opt-in specialist collections `geo`, `science`, `data`, `cad`, `forensics`
//! and `games` (`full` enables all). Extractors are written against the
//! [`plugin`] API; see `CONTRIBUTING.md`. Extractors from other crates are
//! added with [`Registry::with`].

