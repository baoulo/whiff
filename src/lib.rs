/// The report schema identifier written to `whiff.schema`.
pub const SCHEMA: &str = "whiff/1";

/// Cargo features this build of whiff was compiled with.
pub fn enabled_features() -> Vec<&'static str> {
    let mut f = Vec::new();
    for (name, on) in [
        ("common", cfg!(feature = "common")),
        ("geo", cfg!(feature = "geo")),
        ("science", cfg!(feature = "science")),
        ("data", cfg!(feature = "data")),
        ("cad", cfg!(feature = "cad")),
        ("forensics", cfg!(feature = "forensics")),
        ("games", cfg!(feature = "games")),
    ] {
        if on {
            f.push(name);
        }
    }
    f
}

/// The built-in registry, generated by `build.rs` from the `register_*!` lines.
