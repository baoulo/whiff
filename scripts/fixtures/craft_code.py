def write(out, fid, name, data):
    d = os.path.join(out, fid)
    os.makedirs(d, exist_ok=True)
    mode = "wb" if isinstance(data, bytes) else "w"
    with open(os.path.join(d, name), mode, **({} if mode == "wb" else {"encoding": "utf-8", "newline": ""})) as f:
        f.write(data)


def step_sources(out):
    for fid, files in SOURCES.items():
        for name, text in files:
            write(out, fid, name, text)


def step_manifests(out):
    for fid, files in MANIFESTS.items():
        for name, text in files:
            write(out, fid, name, text)


def step_spirv(out):
    """glslang: the compute and fragment shaders of the `glsl` fixtures,
    plus a big-endian copy of the compute module (the byte order SPIR-V
    readers must accept)."""
    work = os.path.join(out, "_spirv")
    os.makedirs(work, exist_ok=True)
    src = dict(SOURCES["glsl"])
    for name, target in [("tide.comp", "tide.comp.spv"), ("water.frag", "water.frag.spv")]:
        path = os.path.join(work, name)
        with open(path, "w", encoding="utf-8") as f:
            f.write(src[name])
        dst = os.path.join(work, target)
        subprocess.run(["glslangValidator", "-V", "--target-env", "vulkan1.2", "-o", dst, path], check=True,
                       stdout=subprocess.DEVNULL)
        with open(dst, "rb") as f:
            write(out, "spirv", target, f.read())
    with open(os.path.join(work, "tide.comp.spv"), "rb") as f:
        le = f.read()
    words = struct.unpack("<%dI" % (len(le) // 4), le)
    write(out, "spirv", "tide.comp.be.spv", struct.pack(">%dI" % len(words), *words))
    # The scratch folder is not a fixture.
    for name in os.listdir(work):
        os.remove(os.path.join(work, name))
    os.rmdir(work)


