//! Generates the built-in registry: every `register_extractor!(T)`,
//! `register_block_decoder!(T)` and `register_analyzer!(T)` line under
//! `src/formats/`, `src/meta/`, `src/text/` and `src/engine/` becomes an entry in
//! `$OUT_DIR/builtin.rs`, gated by the feature of its format group.
//!
//! An explicit, generated list is used instead of linker-section tricks
//! (`inventory`, `linkme`) because whether the linker keeps unreferenced
//! registration objects differs between toolchains and targets.

use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

const MACROS: [(&str, &str); 3] = [
    ("register_extractor!", "extractors"),
    ("register_block_decoder!", "block_decoders"),
    ("register_analyzer!", "analyzers"),
];

struct Entry {
    list: &'static str,
    path: String,
    feature: Option<String>,
}

fn main() {
    let root = PathBuf::from(std::env::var_os("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let src = root.join("src");
    let mut entries = Vec::new();
    for top in ["formats", "meta", "text", "engine"] {
        let dir = src.join(top);
        println!("cargo:rerun-if-changed=src/{top}");
        if dir.is_dir() {
            scan(&src, &dir, &mut entries);
        }
    }

    let mut out = String::from("// @generated by build.rs — do not edit.\n");
    for (_, list) in MACROS {
        let trait_name = match list {
            "extractors" => "Extractor",
            "block_decoders" => "BlockDecoder",
            _ => "Analyzer",
        };
        // One `push` per registered type: long by design.
        let _ = writeln!(out, "#[allow(clippy::vec_init_then_push, clippy::too_many_lines)]");
        let _ = writeln!(out, "pub(crate) fn {list}() -> Vec<&'static dyn crate::plugin::{trait_name}> {{");
        let _ = writeln!(
            out,
            "    #[allow(unused_mut)]\n    let mut v: Vec<&'static dyn crate::plugin::{trait_name}> = Vec::new();"
        );
        for e in entries.iter().filter(|e| e.list == list) {
            if let Some(f) = &e.feature {
                let _ = writeln!(out, "    #[cfg(feature = \"{f}\")]");
            }
            let _ = writeln!(out, "    v.push(&{});", e.path);
        }
        out.push_str("    v\n}\n");
    }
    let out_dir = PathBuf::from(std::env::var_os("OUT_DIR").expect("OUT_DIR"));
    fs::write(out_dir.join("builtin.rs"), out).expect("write builtin.rs");
    fs::write(out_dir.join("catalogue.rs"), catalogue(&root)).expect("write catalogue.rs");
}

/// `(key, family, feature)` rows from `data/formats.tsv` and `data/families.tsv`,
/// keyed by extension and by MIME type, so detection can say which feature
/// would add an extractor for a format this build only identifies.
fn catalogue(root: &Path) -> String {
    println!("cargo:rerun-if-changed=data/formats.tsv");
    println!("cargo:rerun-if-changed=data/families.tsv");
    let rows = |name: &str| -> Vec<Vec<String>> {
        fs::read_to_string(root.join("data").join(name))
            .unwrap_or_default()
            .lines()
            .filter(|l| !l.starts_with('#') && !l.trim().is_empty())
            .map(|l| l.split('\t').map(str::to_string).collect())
            .collect()
    };
    let features: std::collections::HashMap<String, String> =
        rows("families.tsv").into_iter().filter(|r| r.len() > 2).map(|r| (r[0].clone(), r[2].clone())).collect();
    let mut by_ext = std::collections::BTreeMap::new();
    let mut by_mime = std::collections::BTreeMap::new();
    for r in rows("formats.tsv").into_iter().filter(|r| r.len() > 4) {
        let (family, exts, mime) = (&r[1], &r[3], &r[4]);
        let Some(feature) = features.get(family) else { continue };
        for ext in exts.split_whitespace() {
            if ext.chars().all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '-' || c == '.') {
                by_ext
                    .entry(ext.trim_start_matches('.').to_ascii_lowercase())
                    .or_insert((family.clone(), feature.clone()));
            }
        }
        if !mime.is_empty() {
            by_mime.entry(mime.to_ascii_lowercase()).or_insert((family.clone(), feature.clone()));
        }
    }
    let mut out = String::from("// @generated by build.rs from data/*.tsv — do not edit.\n");
    for (name, map) in [("BY_EXTENSION", by_ext), ("BY_MIME", by_mime)] {
        let _ = writeln!(out, "pub(crate) static {name}: &[(&str, &str, &str)] = &[");
        for (k, (family, feature)) in map {
            let _ = writeln!(out, "    ({k:?}, {family:?}, {feature:?}),");
        }
        out.push_str("];\n");
    }
    out
}

fn scan(src: &Path, dir: &Path, entries: &mut Vec<Entry>) {
    let mut paths: Vec<PathBuf> =
        fs::read_dir(dir).expect("read_dir").filter_map(Result::ok).map(|e| e.path()).collect();
    paths.sort();
    for path in paths {
        if path.is_dir() {
            scan(src, &path, entries);
        } else if path.extension().is_some_and(|e| e == "rs") {
            scan_file(src, &path, entries);
        }
    }
}

fn scan_file(src: &Path, file: &Path, entries: &mut Vec<Entry>) {
    let text = fs::read_to_string(file).expect("read source");
    let rel = file.strip_prefix(src).expect("under src");
    for (n, line) in text.lines().enumerate() {
        let code = line.split("//").next().unwrap_or("").trim();
        for (mac, list) in MACROS {
            let Some(pos) = code.find(mac) else { continue };
            // Skip the macro definitions themselves.
            if code.contains("macro_rules") {
                continue;
            }
            let args = &code[pos + mac.len()..];
            let inner = args
                .strip_prefix('(')
                .and_then(|a| a.split(')').next())
                .filter(|a| !a.trim().is_empty() && !a.contains('$'))
                .unwrap_or_else(|| panic!("{}:{}: write `{mac}(TypeName);` on one line", rel.display(), n + 1));
            let (module, feature) = module_path(src, file);
            entries.push(Entry { list, path: format!("{module}::{}", inner.trim()), feature });
        }
    }
}

/// `src/formats/image/qoi.rs` → (`crate::formats::image::qoi`, Some("common")).
/// Every module on the way must be declared `pub(crate) mod` or `pub mod`.
fn module_path(src: &Path, file: &Path) -> (String, Option<String>) {
    let rel = file.strip_prefix(src).expect("under src");
    let mut parts: Vec<String> = rel.iter().map(|p| p.to_string_lossy().into_owned()).collect();
    let last = parts.pop().expect("file name");
    if last != "mod.rs" {
        parts.push(last.trim_end_matches(".rs").to_string());
    }
    let mut feature = None;
    let mut parent_dir = src.to_path_buf();
    for (depth, name) in parts.iter().enumerate() {
        let parent_file = if depth == 0 { src.join("lib.rs") } else { parent_dir.join("mod.rs") };
        let parent_text = fs::read_to_string(&parent_file).unwrap_or_default();
        let lines: Vec<&str> = parent_text.lines().map(str::trim).collect();
        let decl = lines
            .iter()
            .position(|l| l.strip_suffix(';').and_then(|l| l.rsplit_once("mod ")).is_some_and(|(_, m)| m == name));
        let Some(i) = decl else {
            panic!("module `{name}` is not declared in {}", parent_file.display());
        };
        assert!(
            lines[i].starts_with("pub mod") || lines[i].starts_with("pub(crate) mod"),
            "declare `pub(crate) mod {name};` in {} so the built-in registry can reach it",
            parent_file.display()
        );
        // The feature gate of a format group: `#[cfg(feature = "x")]` right above `pub(crate) mod group;`.
        if depth == 1 && parts[0] == "formats" && i > 0 {
            feature = lines[i - 1]
                .strip_prefix("#[cfg(feature = \"")
                .and_then(|r| r.strip_suffix("\")]"))
                .map(str::to_string);
        }
        parent_dir = parent_dir.join(name);
    }
    (format!("crate::{}", parts.join("::")), feature)
}
